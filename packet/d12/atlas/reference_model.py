"""Python mirror of formal/Formal/AlignedSpecification.lean (K3 and D12).

Implements the Lean definitions literally (Sig, pt, lb, InCell, Glue, SamePoint as the
equivalence generated by isometric edge gluings, graph = unit steps inside one cell) and checks
for small parameters:

1. vertex count: K3 7r^2+6rs+2, D12 6(r+2s)^2+2; edge count 3V-6;
2. degree sequence: exactly twelve vertices of degree 5, all others 6;
3. equality (same partition of sites, same edges) with RouteB's independent construction
   (`.worktrees/verify/studies/RouteB/src/aligned_surface.py`, read-only, keyed by edge position);
4. K3: exhaustive literal-path search from Definition 1(a) agrees with s = +-1 (mod r);
   D12: agreement with the known branches (s = qr +- 1, r >= 3 positive; gcd >= 2 negative);
5. RouteB's explicit K3 tube paths, mapped to the cells, are literal paths (2<=r<=8, 2<=s<=14).

Usage: python3 reference_model.py [--route_b PATH_TO_RouteB_SRC]
"""
import json
import sys
from itertools import product
from math import gcd

# ---------------------------------------------------------------- lattice (AIChallengeSpec)


def rot(z):
    return (-z[1], z[0] + z[1])


def rotN(n, z):
    for _ in range(n):
        z = rot(z)
    return z


def add(a, b):
    return (a[0] + b[0], a[1] + b[1])


def sub(a, b):
    return (a[0] - b[0], a[1] - b[1])


UNIT = [(1, 0), (0, 1), (-1, 1), (-1, 0), (0, -1), (1, -1)]


def cross(a, b):
    return a[0] * b[1] - a[1] * b[0]


def walk(p, steps):
    out = []
    for length, k in steps:
        out.append(p)
        p = add(p, rotN(k, (length, 0)))
    return out


# ---------------------------------------------------------------- signatures (Lean defs)

K3_LAB = [[0, 1, 5], [2, 3, 1], [4, 5, 3], [1, 3, 5],
          [11, 7, 6], [7, 9, 8], [9, 11, 10], [11, 9, 7],
          [2, 1, 0, 6, 7, 8], [4, 3, 2, 8, 9, 10], [0, 5, 4, 10, 11, 6]]


def k3_sig(r, s):
    polys = []
    for f in range(11):
        if f < 8:
            polys.append(walk((0, 0), [(r, 0), (r, 2), (r, 4)]))
        else:
            polys.append(walk((0, 0), [(r, 0), (r, 1), (s, 2), (r, 3), (r, 4), (s, 5)]))
    return K3_LAB, polys


D12_LAB = [list(range(12)), [0] + list(range(11, 0, -1))]


def d12_sig(r, s):
    p0 = walk((0, 0), [(s, 0), (r + s, 1), (s, 1), (r + s, 2), (s, 2), (r + s, 3),
                       (s, 3), (r + s, 4), (s, 4), (r + s, 5), (s, 5), (r + s, 0)])
    p1 = walk((0, 0), [(r + s, 0), (s, 0), (r + s, 1), (s, 1), (r + s, 2), (s, 2),
                       (r + s, 3), (s, 3), (r + s, 4), (s, 4), (r + s, 5), (s, 5)])
    return D12_LAB, [p0, p1]


# ---------------------------------------------------------------- generic surface (Lean Sig)


class Surface:
    def __init__(self, lab, poly):
        self.lab, self.poly, self.N = lab, poly, len(lab)
        assert all(len(lab[f]) == len(poly[f]) for f in range(self.N))
        # Sites: lattice points of each closed cell.
        self.sites = []
        self.index = {}
        for f in range(self.N):
            P = poly[f]
            xs = range(min(x for x, _ in P), max(x for x, _ in P) + 1)
            ys = range(min(y for _, y in P), max(y for _, y in P) + 1)
            for z in product(xs, ys):
                if self.in_cell(f, z):
                    self.index[f, z] = len(self.sites)
                    self.sites.append((f, z))
        # Glue(g,i,f,j,m,tau), enumerated: tau is forced by the first corner equation.
        self.glues = []
        for g in range(self.N):
            for i in range(len(poly[g])):
                for f in range(self.N):
                    for j in range(len(poly[f])):
                        if not (self.lb(g, i) == self.lb(f, j + 1) and
                                self.lb(g, i + 1) == self.lb(f, j)):
                            continue
                        for m in range(6):
                            tau = sub(self.pt(f, j + 1), rotN(m, self.pt(g, i)))
                            if add(rotN(m, self.pt(g, i + 1)), tau) == self.pt(f, j):
                                self.glues.append((g, i, f, j, m, tau))
        # EqvGen SamePoint: union-find over all literal SamePoint pairs.
        parent = list(range(len(self.sites)))

        def find(a):
            while parent[a] != a:
                parent[a] = parent[parent[a]]
                a = parent[a]
            return a
        self.same_pairs = 0
        for (g, i, f, j, m, tau) in self.glues:
            for k, (h, z) in enumerate(self.sites):
                if h != g:
                    continue
                w = add(rotN(m, z), tau)
                if (f, w) in self.index:
                    self.same_pairs += 1
                    a, b = find(k), find(self.index[f, w])
                    if a != b:
                        parent[a] = b
        roots = {}
        self.cls = [roots.setdefault(find(k), len(roots)) for k in range(len(self.sites))]
        self.V = len(roots)
        # graph: unit steps inside one cell, between distinct vertices.
        self.adj = [set() for _ in range(self.V)]
        for k, (f, z) in enumerate(self.sites):
            for u in UNIT:
                k2 = self.index.get((f, add(z, u)))
                if k2 is not None and self.cls[k] != self.cls[k2]:
                    self.adj[self.cls[k]].add(self.cls[k2])
                    self.adj[self.cls[k2]].add(self.cls[k])
        self.deg = [len(a) for a in self.adj]

    def pt(self, f, i):
        P = self.poly[f]
        return P[i % len(P)]

    def lb(self, f, i):
        L = self.lab[f]
        return L[i % len(L)]

    def in_cell(self, f, z):
        P = self.poly[f]
        return all(cross(sub(self.pt(f, i + 1), self.pt(f, i)), sub(z, self.pt(f, i))) >= 0
                   for i in range(len(P)))

    def boundary_only(self):
        """Every glued pair of sites lies on cell boundaries (sanity of the convexity remark)."""
        for (g, i, f, j, m, tau) in self.glues:
            for (h, z) in self.sites:
                if h == g and (f, add(rotN(m, z), tau)) in self.index:
                    if all(cross(sub(self.pt(g, a + 1), self.pt(g, a)), sub(z, self.pt(g, a))) > 0
                           for a in range(len(self.poly[g]))):
                        return False
        return True


# ---------------------------------------------------------------- literal paths (Definition 1(a))


def literal_path_exists(S, want_witness=False):
    """Exhaustive search over all literal paths: p0 deg 5, p1 deg 6 adjacent, and each further
    vertex adjacent to the previous two and new.  Checks the end conditions at every even length
    n >= 4.  Every literal path arises this way, so the search is complete."""
    adj, deg = S.adj, S.deg
    sys.setrecursionlimit(100000)
    for p0 in range(S.V):
        if deg[p0] != 5:
            continue
        for p1 in adj[p0]:
            if deg[p1] != 6:
                continue
            path = [p0, p1]
            used = {p0, p1}
            stack = [iter(sorted((adj[p0] & adj[p1]) - used))]
            while stack:
                nxt = next(stack[-1], None)
                if nxt is None:
                    stack.pop()
                    used.discard(path.pop())
                    if len(path) < 2:
                        break
                    continue
                path.append(nxt)
                used.add(nxt)
                n = len(path)
                if n >= 4 and n % 2 == 0 and deg[path[-1]] == 5 and deg[path[-2]] == 6:
                    return list(path) if want_witness else True
                stack.append(iter(sorted((adj[path[-1]] & adj[path[-2]]) - used)))
    return None if want_witness else False


def check_literal(S, p):
    n = len(p)
    ok = n >= 4 and n % 2 == 0 and len(set(p)) == n
    ok = ok and all(p[i + 1] in S.adj[p[i]] for i in range(n - 1))
    ok = ok and all(p[i + 2] in S.adj[p[i]] for i in range(n - 2))
    return ok and S.deg[p[0]] == 5 and S.deg[p[-1]] == 5 and S.deg[p[1]] == 6 and S.deg[p[-2]] == 6


# ---------------------------------------------------------------- comparison with RouteB


def route_b_compare(S, lab, poly, route_b_src):
    """Same partition of sites and same edge set as RouteB aligned_surface.construct."""
    sys.path.insert(0, route_b_src)
    from aligned_surface import construct  # noqa: E402  (read-only external code)
    graph, _counts, vertices = construct(lab, poly, with_keys=True)
    # RouteB's naming of a site: corner label, edge position, or cell interior point.
    def key(f, q):
        P, L = poly[f], lab[f]
        for i, a in enumerate(P):
            b = P[(i + 1) % len(P)]
            vec = sub(b, a)
            length = gcd(abs(vec[0]), abs(vec[1]))
            d = (vec[0] // length, vec[1] // length)
            u, v = L[i], L[(i + 1) % len(L)]
            if q == a:
                return ('v', u)
            for t in range(1, length):
                if q == (a[0] + t * d[0], a[1] + t * d[1]):
                    return ('e', u, v, t) if u < v else ('e', v, u, length - t)
        return ('f', f, *q)
    to_route_b = {}
    for k, (f, z) in enumerate(S.sites):
        idx = vertices[key(f, z)]
        if to_route_b.setdefault(S.cls[k], idx) != idx:
            return False, 'class split in RouteB'
    if len(set(to_route_b.values())) != S.V or len(graph) != S.V:
        return False, 'partition differs'
    for c in range(S.V):
        if {to_route_b[d] for d in S.adj[c]} != set(graph[to_route_b[c]]):
            return False, 'edges differ'
    return True, 'same partition and edges'


# ---------------------------------------------------------------- K3 explicit tube paths (RouteB)


def k3_tube_witnesses(rmax=8, smax=14):
    """RouteB's explicit K3 paths (k3-positive-proof.md), written in tube coordinates
    (hexagon H + j(r,r) is cell 8 + ((2-j) mod 3)), are literal paths in the mirror graph.
    This is the chart map a Lean sufficiency proof would use."""
    checked, bad = 0, []
    for r in range(2, rmax + 1):
        for s in range(2, smax + 1):
            plus, minus = s % r == 1 % r, (s + 1) % r == 0
            if not (plus or minus):
                continue
            S = Surface(*k3_sig(r, s))
            for kind in (['+'] if plus else []) + (['-'] if minus else []):
                if kind == '+':
                    pts = [z for t in range(2 * s - 1) for z in ((0, t), (-1, t + 1))]
                else:
                    pts = [z for t in range(2 * s + 2) for z in ((0, t), (1, t))]
                idx = []
                for z in pts:
                    k = next((S.index[8 + ((2 - j) % 3), (z[0] - j * r, z[1] - j * r)]
                              for j in range(-6, 7)
                              if (8 + ((2 - j) % 3), (z[0] - j * r, z[1] - j * r)) in S.index),
                             None)
                    idx.append(k)
                checked += 1
                if None in idx or not check_literal(S, [S.cls[k] for k in idx]):
                    bad.append((r, s, kind))
    return {'checked': checked, 'bad': bad}


# ---------------------------------------------------------------- main


def run(route_b_src):
    out = {'K3': [], 'D12': []}
    ok_all = True
    for r in range(1, 8):
        for s in range(1, 8):
            lab, poly = k3_sig(r, s)
            S = Surface(lab, poly)
            E = sum(S.deg) // 2
            rec = {'r': r, 's': s, 'V': S.V, 'E': E,
                   'V_expected': 7 * r * r + 6 * r * s + 2,
                   'deg5': S.deg.count(5), 'deg6': S.deg.count(6),
                   'other_deg': sorted(set(S.deg) - {5, 6}),
                   'boundary_only': S.boundary_only()}
            rec['ok_counts'] = (S.V == rec['V_expected'] and E == 3 * S.V - 6 and
                                rec['deg5'] == 12 and rec['deg5'] + rec['deg6'] == S.V)
            if route_b_src:
                rec['route_b'] = route_b_compare(S, lab, poly, route_b_src)
            if r >= 2 and s >= 2 and r <= 6 and s <= 7:
                w = literal_path_exists(S, want_witness=True)
                cond = (s % r == 1 % r) or ((s + 1) % r == 0)
                rec['path'] = w is not None
                rec['K3Pos'] = cond
                rec['agree'] = (w is not None) == cond and (w is None or check_literal(S, w))
                ok_all &= rec['agree']
            ok_all &= rec['ok_counts'] and rec['boundary_only'] and rec.get('route_b', (True,))[0]
            out['K3'].append(rec)
    for r in range(1, 7):
        for s in range(1, 5):
            lab, poly = d12_sig(r, s)
            S = Surface(lab, poly)
            E = sum(S.deg) // 2
            rec = {'r': r, 's': s, 'V': S.V, 'E': E, 'V_expected': 6 * (r + 2 * s) ** 2 + 2,
                   'deg5': S.deg.count(5), 'deg6': S.deg.count(6),
                   'other_deg': sorted(set(S.deg) - {5, 6}),
                   'boundary_only': S.boundary_only()}
            rec['ok_counts'] = (S.V == rec['V_expected'] and E == 3 * S.V - 6 and
                                rec['deg5'] == 12 and rec['deg5'] + rec['deg6'] == S.V)
            if route_b_src:
                rec['route_b'] = route_b_compare(S, lab, poly, route_b_src)
            if S.V <= 1000:
                w = literal_path_exists(S, want_witness=True)
                rec['path'] = w is not None
                if w is not None:
                    assert check_literal(S, w)
                known_pos = r >= 3 and any(s == q * r + e for q in range(1, 10) for e in (1, -1))
                known_neg = gcd(r, s) >= 2
                rec['known'] = 'pos' if known_pos else ('neg' if known_neg else None)
                if rec['known'] is not None:
                    rec['agree'] = rec['path'] == (rec['known'] == 'pos')
                    ok_all &= rec['agree']
            ok_all &= rec['ok_counts'] and rec['boundary_only'] and rec.get('route_b', (True,))[0]
            out['D12'].append(rec)
    out['K3_tube_witnesses'] = k3_tube_witnesses()
    ok_all &= not out['K3_tube_witnesses']['bad']
    out['all_ok'] = ok_all
    return out


if __name__ == '__main__':
    src = None
    if '--route_b' in sys.argv:
        src = sys.argv[sys.argv.index('--route_b') + 1]
    res = run(src)
    print(json.dumps(res, indent=1, default=str))
